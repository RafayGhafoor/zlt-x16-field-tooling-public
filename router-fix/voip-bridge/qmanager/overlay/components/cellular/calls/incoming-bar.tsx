"use client";

import { useTranslation } from "react-i18next";
import { motion } from "motion/react";
import { PhoneCallIcon, PhoneIncomingIcon, PhoneOffIcon } from "lucide-react";

import MaskedText from "@/components/masked-text";
import { Button } from "@/components/ui/button";
import type { CallTerminal } from "@/hooks/use-call-terminal";
import { useReveal } from "@/hooks/use-reveal";
import { displayName } from "@/lib/phone";
import { cn } from "@/lib/utils";

import { CHIP_GLYPH } from "./shapes";

// =============================================================================
// IncomingBar — the two decisions, at the top, while the modem rings
// =============================================================================
// An incoming call is the one state where the page must act without being read.
// The dashboard popup already carried Answer/Reject, but the Calls page — the
// surface a phone bookmarks — did not, so a ringing call there was answerable
// only from the keypad row, which is not what a hand reaches for. This bar is
// deliberately not a "read failed" banner: it carries controls, appears only
// while `call_label === "incoming"`, and disappears the moment the modem moves
// to active, ended or idle.
//
// The ringtone itself is generated by the hook (use-call-terminal), because
// audio must outlive any single component: the bar is the visual half.
// =============================================================================

const K = "calls";

interface IncomingBarProps {
  terminal: CallTerminal;
}

const IncomingBar = ({ terminal }: IncomingBarProps) => {
  const { t } = useTranslation("common");
  const { revealed } = useReveal();
  const state = terminal.state;
  const who = displayName(
    terminal.contacts,
    state?.call_number ?? state?.number ?? ""
  );

  return (
    <motion.div
      initial={{ opacity: 0, y: -8 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ type: "spring", stiffness: 420, damping: 32 }}
      className={cn(
        "flex flex-wrap items-center gap-3 rounded-tile border border-primary/30 bg-primary-container px-4 py-3 text-on-primary-container"
      )}
      role="alert"
      aria-live="assertive"
    >
      <span className="relative flex size-10 flex-none items-center justify-center">
        {/* The pulse is the visual ring: it only runs while this bar is mounted,
            which is exactly while the modem reports an incoming call. */}
        <span className="absolute inset-0 animate-ping rounded-full bg-primary/25" />
        <PhoneIncomingIcon className={cn(CHIP_GLYPH, "relative size-5")} aria-hidden="true" />
      </span>

      <div className="flex min-w-0 flex-1 flex-col">
        <span className="text-[0.6875rem] font-semibold uppercase tracking-[0.06em]">
          {t(`${K}.incoming`)}
        </span>
        <MaskedText
          className="truncate text-lg font-semibold tabular-nums"
          value={who}
          number={who === (state?.call_number ?? state?.number ?? "")}
          revealed={revealed}
        />
      </div>

      <div className="flex flex-none items-center gap-2">
        <Button
          type="button"
          variant="default"
          size="action"
          onClick={() => void terminal.answer()}
          disabled={!terminal.available}
        >
          <PhoneCallIcon className="size-4" />
          {t(`${K}.answer`)}
        </Button>
        <Button
          type="button"
          variant="tonal-destructive"
          size="action"
          onClick={() => void terminal.reject()}
          disabled={!terminal.available}
        >
          <PhoneOffIcon className="size-4" />
          {t(`${K}.reject`)}
        </Button>
      </div>
    </motion.div>
  );
};

export default IncomingBar;